export function createQuoteFromTemplate(
  template: CateringTemplate,
  overrides: Partial<Quote> = {},
  codeNumber = 105
): Quote {
  const weekend = getUpcomingWeekendRange();
  const now = new Date().toISOString();
  return {
    id: overrides.id || `quote-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    code: overrides.code || `ORC-${codeNumber}`,
    clientName: overrides.clientName ?? '',
    clientPhone: overrides.clientPhone ?? '',
    eventTitle: overrides.eventTitle ?? template.name,
    eventDate: overrides.eventDate ?? weekend.saturday,
    eventTime: overrides.eventTime ?? '13:00',
    location: overrides.location ?? '',
    templateId: template.id,
    templateName: template.name,
    guests: overrides.guests ?? template.defaultGuests,
    hours: overrides.hours ?? template.defaultHours,
    status: overrides.status ?? 'rascunho',
    targetMarginPct: overrides.targetMarginPct ?? template.defaultTargetMarginPct,
    manualFinalPrice: overrides.manualFinalPrice ?? null,
    ingredients:
      overrides.ingredients ??
      template.ingredients.map((item) => ({
        ...item,
        enabled: true,
      })),
    supportCosts:
      overrides.supportCosts ??
      template.supportCosts.map((item) => ({
        ...item,
      })),
    notes: overrides.notes ?? '',
    whatsappRawText: overrides.whatsappRawText ?? '',
    createdAt: overrides.createdAt ?? now,
    updatedAt: overrides.updatedAt ?? now,
  };
}

